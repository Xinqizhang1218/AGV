def pose_to_words(pose):
    if len(pose) != 6 or not all(math.isfinite(value) for value in pose):
        raise ValueError("位姿必须包含6个有限数值")
    words = []
    for value in pose:
        high, low = struct.unpack(">HH", struct.pack(">f", value))
        words.extend([low, high])
    return words


def words_to_pose(words):
    if len(words) != 12:
        raise RuntimeError("读回的数据不是12个word")
    return [struct.unpack(">f", struct.pack(">HH", words[i + 1], words[i]))[0]
            for i in range(0, 12, 2)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--start", type=int, default=1, choices=range(1, 41),
                        metavar="1-40", help="仅写指定点，默认1；写完即退出")
    parser.add_argument("--dry-run", action="store_true", help="只打印目标，不连接PLC")
    args = parser.parse_args()
    number = args.start
    if args.dry_run:
        print(f"P{number:02d}: " + ", ".join(f"{v:.8f}" for v in POSES[number - 1]))
        return

    from pymodbus.client import ModbusTcpClient
    # 禁止库自动重发写请求；任何异常均退出，不自动进入下一个点。
    client = ModbusTcpClient(PLC_IP, port=PLC_PORT, timeout=3, retries=0)
    try:
        print("仅写 D1020-D1031；不写 D1002/D1012，不发运动命令。")
        print("请现场确认机器人手动模式、PLC运动任务空闲，且写目标不会触发运动。")
        if input("确认上述状态后输入 y 连接PLC，其他输入退出：").strip() != "y":
            return
        if not client.connect():
            raise RuntimeError("PLC连接失败")
        pose = POSES[number - 1]
        words = pose_to_words(pose)
        print(f"\nP{number:02d} 目标(m/rad): " + ", ".join(f"{v:.8f}" for v in pose))
        answer = input("回车写入这个点；q退出：").strip().lower()
        while answer not in ("", "q"):
            answer = input("请输入回车或q：").strip().lower()
        if answer == "q":
            return
        # 一次写6个float32，地址只覆盖1020至1031。
        result = client.write_registers(address=POSE_ADDRESS, values=words)
        if result.isError():
            raise RuntimeError(f"写入返回异常：{result}")
        result = client.read_holding_registers(address=POSE_ADDRESS, count=12)
        if result.isError():
            raise RuntimeError(f"读回返回异常：{result}")
        if list(result.registers) != words:
            raise RuntimeError(f"读回不一致：期望{words}，实际{result.registers}")
        print("写入及读回一致：" + ", ".join(f"{v:.8f}" for v in words_to_pose(result.registers)))
        print("这是目标寄存器读回，不是机器人实际位置。")
        print(f"\nP{number:02d} 已写完，程序退出；未发送运动启动命令。")
    except (Exception, KeyboardInterrupt) as error:
        print(f"\n已停止：{error}")
        print("若在写入/读回时中断，写入结果可能未知；先核对PLC，不要直接重试。")
        raise SystemExit(1)
    finally:
        client.close()


if __name__ == "__main__":
    main()
